export function createWorkbookSnapshots(): PortfolioSnapshot[] {
  const sequenceByDate = new Map<string, number>();
  return HISTORY_ROWS.map(([asOfDate, ...values], index) => {
    const sequence = (sequenceByDate.get(asOfDate) ?? 0) + 1;
    sequenceByDate.set(asOfDate, sequence);
    const allocation = Object.fromEntries(
      SNAPSHOT_KEYS.map((key, keyIndex) => [key, values[keyIndex]]),
    ) as unknown as PortfolioSnapshotValues;
    return {
      ...allocation,
      id: `workbook-snapshot-${index + 1}`,
      asOfDate,
      sequence,
      source: "XLSX_IMPORT",
      createdAt: IMPORTED_AT,
      updatedAt: IMPORTED_AT,
      note: index === HISTORY_ROWS.length - 1 ? "Imported from Portofolio.xlsx / Income History" : undefined,
    };
  });
}

